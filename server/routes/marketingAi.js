const express = require('express');
const {
  verifyAdminApiAuth,
  requireAdmin,
  requireAdminTwoFactorSatisfied,
  requireAdminSessionValid,
  requirePermission,
} = require('../authMiddleware');

const router = express.Router();

const SYSTEM_INSTRUCTION = `You write marketing copy for RemoEdPH. RemoEdPH is live one-on-one English classes for children aged 3-6 with real teachers. Families are in Taiwan, Japan, South Korea, and Southeast Asia.
Your tone is warm, clear, and useful for parents.
Lesson characters are Remo, Ed, Sofie, and Teacher Grace.
Describe live classes with real teachers. Do not call RemoEd AI-powered.`;

function getModels() {
  const models = [
    process.env.GEMINI_MODEL || 'gemini-2.5-flash',
    'gemini-3.6-flash',
  ];
  return [...new Set(models)];
}

router.post(
  '/ai-generate',
  verifyAdminApiAuth,
  requireAdmin,
  requireAdminTwoFactorSatisfied,
  requireAdminSessionValid,
  requirePermission('growth.ai_settings'),
  async (req, res) => {
    try {
      const body = req.body || {};
      const contentType = String(body.contentType || 'Facebook Group Post').slice(0, 80);
      const targetMarket = String(body.targetMarket || 'General International (Asia)').slice(0, 80);
      const topicDetails = String(body.topicDetails || '').trim().slice(0, 2000);

      if (!topicDetails) {
        return res.status(400).json({
          success: false,
          message: 'Topic details are required.',
        });
      }

      const apiKey = process.env.GEMINI_API_KEY;
      if (!apiKey) {
        return res.status(500).json({
          success: false,
          message: 'Gemini API key is missing in server environment.',
        });
      }

      const prompt = [
        'Task: Create ' + contentType,
        'Target market: ' + targetMarket,
        'Points to include: ' + topicDetails,
        'Write 2 variations. Each one needs a clear next step for the parent.',
      ].join('\n');

      let response;
      let data;

      for (const model of getModels()) {
        response = await fetch(
          'https://generativelanguage.googleapis.com/v1beta/models/' + model + ':generateContent',
          {
            method: 'POST',
            headers: {
              'Content-Type': 'application/json',
              'x-goog-api-key': apiKey,
            },
            body: JSON.stringify({
              systemInstruction: { parts: [{ text: SYSTEM_INSTRUCTION }] },
              contents: [{ role: 'user', parts: [{ text: prompt }] }],
            }),
          }
        );

        data = await response.json();
        if (response.status !== 404) break;
        console.error('Gemini model not found: ' + model);
      }

      if (!response.ok) {
        console.error('Gemini API Error:', JSON.stringify(data));
        return res.status(response.status).json({
          success: false,
          message: (data.error && data.error.message) || 'Error response from Gemini API.',
        });
      }

      const generatedText = ((data.candidates && data.candidates[0] && data.candidates[0].content && data.candidates[0].content.parts) || [])
        .map((part) => part.text || '')
        .join('')
        .trim();

      if (!generatedText) {
        const reason = (data.promptFeedback && data.promptFeedback.blockReason)
          || (data.candidates && data.candidates[0] && data.candidates[0].finishReason);
        console.error('Gemini returned no text. Reason:', reason);
        return res.status(500).json({
          success: false,
          message: reason
            ? 'No content was generated (' + reason + '). Try rewording the topic.'
            : 'No content was generated by Gemini.',
        });
      }

      return res.json({
        success: true,
        content: generatedText,
      });
    } catch (error) {
      console.error('Error generating marketing copy:', error.message || error);
      return res.status(500).json({
        success: false,
        message: 'Failed to generate content.',
      });
    }
  }
);

module.exports = router;
