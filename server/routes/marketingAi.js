const express = require('express');
const router = express.Router();

// Make sure the JSON body can be read
router.use(express.json());

const SYSTEM_INSTRUCTION = `You are an expert ESL Marketing Specialist for RemoEdPH, a premier online English learning platform for children aged 3-6 in Taiwan, Japan, South Korea, and Southeast Asia.
Your tone is warm, professional, encouraging, and highly converting for parents.
RemoEdPH features interactive AI character-led lessons with characters Remo the Robot, Ed, and Sophia.`;

// Models are tried in order. Override the first one with GEMINI_MODEL in .env
function getModels() {
  const models = [
    process.env.GEMINI_MODEL || 'gemini-2.5-flash',
    'gemini-3.6-flash'
  ];
  return [...new Set(models)];
}

router.post('/api/admin/marketing/ai-generate', async (req, res) => {
  try {
    const { contentType, targetMarket, topicDetails } = req.body || {};

    if (!topicDetails || !topicDetails.trim()) {
      return res.status(400).json({
        success: false,
        message: 'Topic details are required.'
      });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return res.status(500).json({
        success: false,
        message: 'Gemini API key is missing in server environment.'
      });
    }

    const prompt = `
Task: Create ${contentType || 'a marketing post'}
Target Market: ${targetMarket || 'General International (Asia)'}
Context / Topic: ${topicDetails}

Please generate 2 distinct variations of the copy with emojis, clear formatting, engaging hooks, and actionable call-to-action.
`.trim();

    let response;
    let data;

    for (const model of getModels()) {
      response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'x-goog-api-key': apiKey
          },
          body: JSON.stringify({
            systemInstruction: { parts: [{ text: SYSTEM_INSTRUCTION }] },
            contents: [{ role: 'user', parts: [{ text: prompt }] }]
          })
        }
      );

      data = await response.json();

      // Only fall back to the next model if this one was not found
      if (response.status !== 404) break;
      console.error(`Gemini model not found: ${model}`);
    }

    if (!response.ok) {
      console.error('Gemini API Error:', JSON.stringify(data));
      return res.status(response.status).json({
        success: false,
        message: data.error?.message || 'Error response from Gemini API.'
      });
    }

    const generatedText = (data.candidates?.[0]?.content?.parts || [])
      .map(p => p.text || '')
      .join('')
      .trim();

    if (!generatedText) {
      const reason = data.promptFeedback?.blockReason || data.candidates?.[0]?.finishReason;
      console.error('Gemini returned no text. Reason:', reason);
      return res.status(500).json({
        success: false,
        message: reason
          ? `No content was generated (${reason}). Try rewording the topic.`
          : 'No content was generated by Gemini.'
      });
    }

    return res.json({
      success: true,
      content: generatedText
    });

  } catch (error) {
    console.error('Error generating AI marketing content:', error.message || error);
    return res.status(500).json({
      success: false,
      message: error.message || 'Failed to generate content. Please check server logs or API key setup.'
    });
  }
});

module.exports = router;